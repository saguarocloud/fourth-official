export interface Dot {
  readonly x: number;
  readonly y: number;
  readonly lit: boolean;
}

export interface DotMatrix {
  readonly columns: number;
  readonly rows: number;
  readonly dots: readonly Dot[];
}

function glyphFor(char: string): readonly string[] {
  return GLYPHS[char.toUpperCase()] ?? GLYPHS[FALLBACK]!;
}

/** Lay text out on a dot grid, one blank column between characters. */
export function layoutText(text: string): DotMatrix {
  const glyphs = Array.from(text).map(glyphFor);
  const columns =
    glyphs.length === 0 ? 0 : glyphs.length * GLYPH_WIDTH + (glyphs.length - 1) * GLYPH_GAP;
  const lit = new Set<string>();
  glyphs.forEach((rows, index) => {
    const offset = index * (GLYPH_WIDTH + GLYPH_GAP);
    rows.forEach((row, y) => {
      Array.from(row).forEach((bit, x) => {
        if (bit === "1") lit.add(`${offset + x},${y}`);
      });
    });
  });
  const dots: Dot[] = [];
  for (let y = 0; y < GLYPH_HEIGHT; y += 1) {
    for (let x = 0; x < columns; x += 1) {
      dots.push({ x, y, lit: lit.has(`${x},${y}`) });
    }
  }
  return { columns, rows: GLYPH_HEIGHT, dots };
}
